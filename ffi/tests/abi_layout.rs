//! The ABI layout pin: the shipped header, compiled by a real C compiler,
//! against the `#[repr(C)]` mirror in `ffi/src/abi.rs`.
//!
//! `tests/abi.rs` drives the exports; this test checks what their arguments are
//! made of. It writes a C file of `_Static_assert`s - one for every struct's
//! `sizeof`, one per field for its `offsetof` and its own `sizeof`, and a
//! `_Generic` check that the field's category (integer, float, pointer) is the
//! one the Rust side declares - and asks a C compiler to compile it against
//! `include/reconl/reconl.h`. A field added, removed, reordered or retyped on
//! one side and not the other stops this test, which is the only way an ABI
//! stays a contract. The same file asserts every macro, constant and enum member
//! the header exports against the Rust value the implementation uses, so a
//! renumbered code, flag or enumerator fails the same way a retyped field does.
//!
//! It skips, with a printed reason, when the host has no C compiler, the way the
//! d3d11 legs skip without a usable device. On failure the generated file is
//! left in `CARGO_TARGET_TMPDIR` and its path printed, so a red run is
//! diagnosable from the compiler's own messages.

