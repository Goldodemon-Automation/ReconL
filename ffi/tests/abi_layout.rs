// `f!` is one table row: the C field name, the Rust offset, the Rust field
// size, and the field's category. `as "name"` is for the two fields whose C
// names are not their Rust names (`ReconLBase::type` and `ReconLLight::type`).
macro_rules! f {
    ($t:ty, $f:ident, $ty:ty, $kind:literal) => {
        (stringify!($f), offset_of!($t, $f), size_of::<$ty>(), $kind)
    };
    ($t:ty, $f:ident as $name:literal, $ty:ty, $kind:literal) => {
        ($name, offset_of!($t, $f), size_of::<$ty>(), $kind)
    };
}

#[test]
fn the_header_and_the_rust_mirror_agree_on_every_struct_layout() {
    let path = write_generated(&generated());
    match compile(&path) {
        Compile::Passed => {}
        Compile::NoCompiler => eprintln!(
            "no C compiler on this host (tried CC, cc, gcc, clang); \
             skipping the header/Rust layout check"
        ),
        Compile::Failed(report) => panic!(
            "the shipped header and the Rust mirror in ffi/src/abi.rs disagree about \
             the ABI layout. The generated C (left at {}) did not compile:\n\n{report}",
            path.display()
        ),
    }
}

enum Compile {
    Passed,
    NoCompiler,
    Failed(String),
}

/// Compile the generated file with the first compiler that runs it. A compiler
/// that is present but rejects the file is a failure, not a skip: a broken
/// toolchain must not silently retire the check.
fn compile(c_file: &Path) -> Compile {
    let include = Path::new(env!("CARGO_MANIFEST_DIR")).join("../include");
    let mut candidates = Vec::new();
    if let Ok(cc) = std::env::var("CC") {
        if !cc.trim().is_empty() {
            candidates.push(cc);
        }
    }
    candidates.extend(["cc", "gcc", "clang", "x86_64-w64-mingw32-gcc"].map(str::to_string));

    let mut report = String::new();
    let mut ran = false;
    for cc in candidates {
        let Ok(out) = Command::new(&cc)
            .args(["-std=c11", "-fsyntax-only", "-I"])
            .arg(&include)
            .arg(c_file)
            .output()
        else {
            continue;
        };
        ran = true;
        if out.status.success() {
            return Compile::Passed;
        }
        let _ = write!(report, "--- {cc} ---\n{}", String::from_utf8_lossy(&out.stderr));
    }
    if ran {
        Compile::Failed(report)
    } else {
        Compile::NoCompiler
    }
}

/// The file is per-process because the suite runs fully parallel.
fn write_generated(source: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR"));
    std::fs::create_dir_all(&dir).expect("create CARGO_TARGET_TMPDIR");
    let path = dir.join(format!("abi_layout.generated.{}.c", std::process::id()));
    std::fs::write(&path, source).expect("write the generated C file");
    path
}

