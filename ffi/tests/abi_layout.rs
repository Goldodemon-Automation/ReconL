/// A table row per constant: the header's spelling, the Rust value.
macro_rules! values {
    ($c:expr, $( $cname:literal = $rust:expr ),* $(,)?) => {
        $( value($c, $cname, $rust); )*
    };
}

/// One `_Static_assert` for a C macro or enumerator, against the Rust value the
/// implementation uses. The message is the constant's own name, so the compiler
/// says which value drifted.
fn value(c: &mut String, cname: &str, rust: i64) {
    let _ = writeln!(c, "_Static_assert({cname} == {rust}, \"{cname}: value\");");
}

